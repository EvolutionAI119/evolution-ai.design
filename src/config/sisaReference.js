/** 在参考顶廓线上按 xNorm 线性插值取 z_top_norm */
export function sampleTopNorm(xNorm) {
  const x = Math.min(Math.max(xNorm, 0), 1)
  const n = SISA_X_NORM.length
  const step = 1 / (n - 1)
  const f = x / step
  const i = Math.min(Math.floor(f), n - 2)
  const t = f - i
  return SISA_Z_TOP_NORM[i] * (1 - t) + SISA_Z_TOP_NORM[i + 1] * t
}

/**
 * 像真度量化：平台生成的顶廓线（z/H 归一化，与 x_norm 同长 N）对 SISA 真车顶廓线的 RMSE。
 * 传入数组长度可不同于 200，内部重采样到参考网格。
 * 用法见 README_SISA_REFERENCE.md 第 4 节——把「像不像真车」从主观变成可量化。
 */
export function evalTopRMSE(myZTopNorm) {
  if (!Array.isArray(myZTopNorm) || myZTopNorm.length < 2) return NaN
  const n = myZTopNorm.length
  let acc = 0
  for (let i = 0; i < n; i++) {
    const xNorm = i / (n - 1)
    // 输入网格 → 参考网格插值
    const srcF = xNorm * (n - 1)
    const si = Math.min(Math.floor(srcF), n - 2)
    const t = srcF - si
    const mine = myZTopNorm[si] * (1 - t) + myZTopNorm[si + 1] * t
    const ref = sampleTopNorm(xNorm)
    const d = mine - ref
    acc += d * d
  }
  return Math.sqrt(acc / n)
}

